from dataclasses import dataclass
from typing import Any


@dataclass
class GelSightSensorData:
    """Data container for a GelSight sensor."""

    output: dict[str, Any] = None
    """The retrieved sensor data with sensor types as key.

    This is defined inside the corresponding sensor cfg class.
    For GelSight sensors the defaults are "camera_depth", "height_map", "tactile_rgb", "marker_motion" and "markers_rgb".
    - camera_depth: depth image from the sensor camera
    - height_map: Generated by the sensor camera. Shape = the camera resolution specified in the SensorCameraCfg.
    - tactile_rgb: Tactile RGB image. Shape = tactile_img_resolution specified in the OpticalSimulator class.
    - marker_motion: Initial and current positions of the gelpad markers.
        Shape (num_envs, 2, num_markers, 2)
        - dim = 1: (initial, current markers)
        - dim = 3: marker pos (x,y) in the image (x = width, y = height)
    - markers_rgb: Tactile RGB image with marker motion field visualization overlay
    """
